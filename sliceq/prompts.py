LANG_NAMES = {
    "en": "英语", "zh": "中文（简体）", "ja": "日语",
    "ko": "韩语", "es": "西班牙语", "fr": "法语",
    "de": "德语", "ru": "俄语", "pt": "葡萄牙语",
}


def translate_prompt(lines: list[str], target_lang: str = "en",
                     source_lang: str = "zh") -> str:
    """构造一批字幕的翻译提示词。

    ⚠️ 编号必须显式写出来并强调"逐行对应"。
       实测：不写编号时模型会自行合并/拆分句子，
       20 条能变成 17 条 —— 而返回结果里**没有任何报错**，
       只是字幕从某一行开始整体错位。
    """
    tgt = LANG_NAMES.get(target_lang, target_lang)
    src = LANG_NAMES.get(source_lang, source_lang)
    body = "\n".join(f"{i}. {t}" for i, t in enumerate(lines, 1))
    return f"""\
把下面的{src}字幕逐行翻译成{tgt}。共 {len(lines)} 行。

{body}

只输出 {len(lines)} 行，每行格式为 `编号. 译文`。"""


