def refine_prompt(profile: str, clip_start: float, clip_end: float,
                  hint: str = "") -> str:
    """构造精析的用户提示词。

    ⚠️ 同样要交代时间基准：精析送的是"切出来的副本"，
       模型给的秒数是相对副本的，调用方必须自己加回 clip_start。
    """
    hint_line = f"\n粗筛给出的理由（供参考，你可以推翻它）：{hint}\n" if hint else ""
    return f"""\
用户的内容画像：
{profile}
{hint_line}
这段素材整体对应原片的 {clip_start:.1f}s ~ {clip_end:.1f}s，
你收到的是这一段（时长 {clip_end - clip_start:.1f} 秒）。

请判断这一段是否真的适合切片，给出精确的起止时间与质量评分。

{_REFINE_JSON_SPEC}"""


